"""Run AFTER make_masks.py: inlines the 4 masks into css/hero-masks.css."""
import base64
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
names = {"solid-a": "--hero-solid-a", "solid-b": "--hero-solid-b", "solid-c": "--hero-solid-c", "code": "--hero-code"}
out = ["/* AUTO-GENERATED by tools/make_masks.py + tools/build_mask_css.py. Do not edit by hand. */", ":root {"]
for k, v in names.items():
    b = base64.b64encode((ROOT / f"tools/hero-{k}.png").read_bytes()).decode()
    out.append(f'  {v}: url("data:image/png;base64,{b}");')
out.append("}")
(ROOT / "css/hero-masks.css").write_text("\n".join(out) + "\n")
